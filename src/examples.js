// Example programs shown in the editor. Each one is also executed by the tests.

const NL = String.fromCharCode(10);
const program = (lines) => lines.join(NL) + NL;

export const EXAMPLES = {
  'Hello, world': program([
    '; Print a string one character at a time.',
    '        MOV A, text      ; A points at the first letter',
    'loop:   MOV B, [A]       ; load the byte A points at',
    '        CMP B, 0',
    '        JZ done          ; a zero byte ends the string',
    '        OUTC B',
    '        INC A',
    '        JMP loop',
    'done:   HLT',
    'text:   DB "Hello, world!", 0',
  ]),
  'Fibonacci': program([
    '; Print every Fibonacci number that fits in one byte.',
    '        MOV A, 0',
    '        MOV B, 1',
    'next:   OUT A',
    '        MOV C, A',
    '        ADD C, B         ; C = A + B',
    '        JC done          ; carry set: the sum passed 255',
    '        MOV A, B',
    '        MOV B, C',
    '        JMP next',
    'done:   OUT B',
    '        HLT',
  ]),
  'Multiply (subroutine)': program([
    '; There is no MUL instruction, so build one with CALL and RET.',
    '        MOV A, 6',
    '        MOV B, 7',
    '        CALL mul',
    '        OUT C            ; prints 42',
    '        HLT',
    '',
    '; C = A * B by repeated addition. Destroys B.',
    'mul:    MOV C, 0',
    '        CMP B, 0',
    'again:  JZ back',
    '        ADD C, A',
    '        DEC B',
    '        JMP again',
    'back:   RET',
  ]),
  'Diagonal line': program([
    '; The screen is memory 0xE0 to 0xFF: two bytes per row, one bit per pixel.',
    '        MOV A, 0xE0      ; left-hand byte of row 0',
    '        MOV B, 0x80      ; leftmost pixel',
    'left:   MOV [A], B',
    '        ADD A, 2         ; same byte, next row',
    '        SHR B            ; one pixel to the right',
    '        JNZ left',
    '        INC A            ; switch to the right-hand byte',
    '        MOV B, 0x80',
    'right:  MOV [A], B',
    '        ADD A, 2',
    '        SHR B',
    '        JNZ right',
    '        HLT',
  ]),
  'Checkerboard': program([
    '; Fill the screen with alternating pixels.',
    '        MOV A, 0xE0',
    '        MOV B, 0xAA      ; 10101010',
    'row:    MOV [A], B',
    '        INC A',
    '        MOV [A], B',
    '        INC A            ; wraps to 0 after 0xFF and sets the zero flag',
    '        JZ done',
    '        NOT B            ; 01010101 for the next row',
    '        JMP row',
    'done:   HLT',
  ]),
  'Binary counter (runs forever)': program([
    '; Count upward and show the bits on the middle of the screen.',
    '; Slow the clock down to watch the carries ripple.',
    '        MOV A, 0',
    'loop:   MOV [0xEF], A',
    '        MOV [0xF1], A',
    '        INC A',
    '        JMP loop',
  ]),
};
